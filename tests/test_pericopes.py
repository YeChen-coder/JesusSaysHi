"""USFM sections: headings, parallels, red letters, footnotes, and verses spread over lines."""

from pathlib import Path

import pytest

from pericopes import read_sections
from scripture import read_verses

SAMPLE = r"""\id MAT Autogenerated BSB
\h Matthew
\mt1 Matthew
\c 11
\s1 Rest for the Weary
\r (\ref Luke 10:21–22|LUK 10:21-22\ref*)
\p \v 28 \wj “Come to Me, all you who are weary and burdened,\wj* he said.\f + \fr 11:28 \ft A note.\f*
\q1 \wj and I will give you rest.\wj*
\v 29 Then they left.
\c 12
\p \v 1 At that time.
\v 2
\s1 Lord of the Sabbath
\p \v 3 \wj “Have you not read?”\wj*
"""


@pytest.fixture
def sections(tmp_path):
    (tmp_path / "MAT.usfm").write_text(SAMPLE, encoding="utf-8")
    return read_sections(tmp_path, ("Matthew",))


def test_sections_follow_headings_and_may_cross_a_chapter(sections):
    assert [s.title for s in sections] == ["Rest for the Weary", "Lord of the Sabbath"]
    first = sections[0]
    assert [(v.chapter, v.verse) for v in first.verses] == [(11, 28), (11, 29), (12, 1)]
    assert first.ref == "Matthew 11:28-12:1"
    assert first.parallels == ["Luke 10:21–22"]


def test_markers_and_footnotes_are_removed_and_red_letters_counted(sections):
    verse = sections[0].verses[0]
    assert verse.text == ("“Come to Me, all you who are weary and burdened, he said. "
                          "and I will give you rest.")
    assert verse.jesus_words == 16 and verse.words == 18
    assert sections[0].metadata()["jesus_speaks"] == "yes"
    assert sections[1].jesus_share == 1.0


def test_a_red_letter_span_carries_across_verses(tmp_path):
    (tmp_path / "MAT.usfm").write_text(
        "\\c 5\n\\s1 Sermon\n\\p \\v 1 He said, \\wj “Blessed are the poor,\n"
        "\\v 2 blessed are the meek.”\\wj* Then he sat.\n", encoding="utf-8")
    verses = read_sections(tmp_path, ("Matthew",))[0].verses
    assert [(v.jesus_words, v.words) for v in verses] == [(4, 6), (4, 7)]


def test_document_has_a_header_and_one_line_per_verse(sections):
    lines = sections[1].document().splitlines()
    assert lines == ["Matthew 12:3 · Lord of the Sabbath", "Matthew 12:3 “Have you not read?”"]
    assert sections[0].filename() == "Matthew 11.28 Rest for the Weary.txt"


BSB = Path(__file__).resolve().parents[1] / "data" / "raw"


@pytest.mark.skipif(not (BSB / "usfm" / "bsb_usfm" / "MAT.usfm").is_file(), reason="BSB USFM not downloaded")
def test_real_usfm_matches_the_plain_text_edition_verse_for_verse():
    from pericopes import normalize

    sections = read_sections(BSB / "usfm" / "bsb_usfm")
    usfm = {(s.book, v.chapter, v.verse): v.text for s in sections for v in s.verses}
    plain = {v.key: v.text for v in read_verses(BSB / "bsb.txt")}
    assert len(sections) == 487
    assert usfm.keys() == plain.keys()
    mismatched = [key for key in plain if normalize(usfm[key]) != normalize(plain[key])]
    # The two official exports differ in wording here ("removed it . . .)" vs "removed it)").
    assert mismatched == [("John", 21, 7)]
    canonical = read_sections(BSB / "usfm" / "bsb_usfm", canonical=plain)
    assert {(s.book, v.chapter, v.verse): v.text for s in canonical for v in s.verses} == plain
